import "../eval/rulesOnly.js";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { config } from "../config.js";
import { loadSeedData } from "../data/seed.js";
import { auditConversation, type Finding } from "./audit.js";
import { ScenarioDriver } from "./driver.js";
import { runScript, type Check } from "./checks.js";
import { runAllVariations } from "./variations.js";

/** `npm run scenario`: runs the demo script, the variations and the audit, and writes docs/evidence.md. */
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const mark = (c: Check) => `- ${c.pass ? "✅" : "❌"} ${c.label}`;
const clip = (s: string, n = 150) => (s.length > n ? `${s.slice(0, n - 1)}…` : s);

const seed = await loadSeedData(config.dataDir);
const dir = await mkdtemp(path.join(os.tmpdir(), "willow-scenario-"));
const driver = await ScenarioDriver.start(dir);
try {
  const { steps, invariants, final } = await runScript(driver, {
    // Restart the whole process mid-script to show nothing is lost.
    before: async (n) => {
      if (n === 6) await driver.restart();
    },
  });
  const variations = await runAllVariations();

  // ---- audit: the demo script, then every variation ----
  const audits = [
    { name: "Demo script (steps 0-11)", ...auditConversation(final, seed) },
    ...variations.map((v) => ({ name: `Variation: ${v.id}`, ...auditConversation(v.view, seed) })),
  ];
  const findings: (Finding & { name: string })[] = audits.flatMap((a) => a.findings.map((f) => ({ ...f, name: a.name })));
  const handoffsAudited = audits.reduce((n, a) => n + a.handoffsAudited, 0);

  const scriptChecks = [...steps.flatMap((s) => s.checks), ...invariants];
  const failedScript = scriptChecks.filter((c) => !c.pass);
  const badVariations = variations.filter((v) => !v.correct || !v.safeFailure);
  const ok = failedScript.length === 0 && badVariations.length === 0 && findings.length === 0;

  const md = [
    "# Test evidence",
    "",
    "Generated by `npm run scenario` (the same definitions run inside `npm test`).",
    "Scenario clock: Wednesday, November 4, 2026, 10:00 a.m. Pacific. Everything runs against the real HTTP API with a fresh store per conversation.",
    "",
    `**Result: ${ok ? "everything passes" : "FAILURES BELOW"}.**`,
    "",
    `| | |`,
    `|---|---|`,
    `| Demo script, steps 0-11, one conversation (server restarted before step 6) | ${scriptChecks.length - failedScript.length} of ${scriptChecks.length} checks pass |`,
    `| Variations and paraphrases | ${variations.filter((v) => v.correct).length} of ${variations.length} behave as wanted; ${variations.filter((v) => v.safeFailure).length} of ${variations.length} meet the safety floor |`,
    `| **Avoidable staff follow-ups** (audit) | **${findings.length}** across ${audits.length} conversations and ${handoffsAudited} handoffs |`,
    "",
    "## 1. Demo script: step table",
    "",
    "| # | From | Input | Agent reply | Handoff effect | Checks |",
    "|---|------|-------|-------------|----------------|--------|",
    ...steps.map(
      (s) =>
        `| ${s.n} | ${s.from} | ${cell(s.input)} | ${s.reply ? cell(s.reply) : "(none; saved in thread)"} | ${cell(s.handoffEffect)} | ${s.checks.filter((c) => c.pass).length}/${s.checks.length} |`,
    ),
    "",
    "### What each step must do, and the checks that prove it",
    "",
    ...steps.flatMap((s) => [`#### Step ${s.n}: ${clip(s.input, 70)}`, "", `*Expected:* ${s.expected}`, "", ...s.checks.map(mark), ""]),
    "### Whole-conversation checks",
    "",
    ...invariants.map(mark),
    "",
    "## 2. Variations and paraphrases",
    "",
    `${variations.length} situations written independently of the rules, each run in its own fresh store. Every case has **must** checks (the behavior we want) and **safe** checks (the floor for any failure: no wrong action, advice or false claim).`,
    "",
    "| Category | What Alex said (last message) | Assistant's reply | Wanted | Safe |",
    "|---|---|---|---|---|",
    ...variations.map(
      (v) => `| ${v.category} | ${cell(clip(v.messages.at(-1)!, 90))} | ${cell(clip(v.replies.at(-1)!, 170))} | ${v.correct ? "✅" : "❌"} | ${v.safeFailure ? "✅" : "❌"} |`,
    ),
    "",
    ...variations.filter((v) => !v.correct || !v.safeFailure).flatMap((v) => [`**${v.id}**`, ...[...v.must, ...v.safe].filter((c) => !c.pass).map(mark), ""]),
    "**History, stated plainly.** These cases were written and run *before* any change to the agent. The first run was **13 of 15** as wanted (15 of 15 safe). The two misses:",
    "",
    '1. *"Never mind about Tuesday, how about the following Monday?"* created a second, bogus request (reason "tuesday", Mon Nov 9). Two bugs: the reason reader treated "about Tuesday" as a reason, and "following Monday" resolved to the wrong Monday. A third problem: my own safety check for this case was too lenient and let it through (it only looked at the first request). Fixed: dates are never reasons; "the following X" is relative to the request being changed, or the agent asks for a day; the check now requires exactly one request.',
    '2. *"need more lisinopril please"* was not recognized as a refill (it fell back to offering staff). Fixed: a medication from the record plus a need for more of it is a refill, while "should I take more lisinopril?" stays a clinical question.',
    "",
    "Earlier in this hardening pass, probing found and fixed: a false clinical handoff for *\"I'm tired of waiting for a callback\"*, *\"can I take my daughter with me to the appointment?\"* being read as an appointment request, and the UI claiming an emergency was \"logged\" when its handoff had failed to save.",
    "",
    "## 3. Avoidable staff follow-ups (audit)",
    "",
    "An avoidable follow-up is any extra message staff would have to send Alex because the agent **missed a detail**, **created a duplicate request**, or **recorded something incorrectly**. `api/src/scenario/audit.ts` reads each finished conversation like a staff member and checks, per handoff:",
    "",
    "- **Required fields** for the type are present (appointment: reason, provider, date, window; refill: medication, dose, frequency, pharmacy, refills left; clinical: the question; billing: balance; emergency: signals and Alex's words).",
    "- **Nothing Alex said was dropped:** every blood-pressure reading and duration in his messages reached the record, a time he asked for that matches no slot is in the note, supply/pharmacy remarks and symptoms mentioned with a request are in the note.",
    "- **Values are correct against the record:** refill medication/dose/frequency/pharmacy/refills match the record; the provider is his; the date is not in the past or a closed day; a chosen slot is really open; billing matches the balance; every source link points at one of Alex's messages.",
    "- **No duplicates:** no two open requests are the same request.",
    "- **Alex was never asked for what is on file** (date of birth, phone, pharmacy, dose, medication, insurance, provider, or the reason when blood pressure was already mentioned).",
    "",
    "| Conversation | Handoffs audited | Avoidable follow-ups |",
    "|---|---|---|",
    ...audits.map((a) => `| ${a.name} | ${a.handoffsAudited} | ${a.findings.length} |`),
    `| **Total** | **${handoffsAudited}** | **${findings.length}** |`,
    "",
    ...(findings.length ? ["Findings:", ...findings.map((f) => `- ❌ ${f.name}: [${f.kind}] ${f.detail}`), ""] : []),
    `**Result: ${findings.length} avoidable staff follow-ups** across the ${audits.length} conversations above.`,
    "",
    "What this does and does not show:",
    "",
    "- It is a checklist written by the same person who wrote the agent, not a clinic staff member's judgment. It shows that nothing *on this list* was missed, in *these* conversations. It says nothing about messages nobody wrote yet.",
    "- It can detect problems: `api/test/audit.test.ts` injects a dropped pharmacy, reading, duration or medication, a duplicate request, a wrong dose/refills/pharmacy/medication, a past or weekend date, a slot that isn't open, a bogus source link and a question for known data, and requires the audit to flag each one (and to flag nothing on a clean conversation).",
    "",
  ].join("\n");

  const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../../docs/evidence.md");
  await mkdir(path.dirname(out), { recursive: true });
  await writeFile(out, md, "utf8");

  console.log(md.split("\n").slice(0, 14).join("\n"));
  console.log(`\nWrote ${path.relative(process.cwd(), out)}`);
  if (!ok) {
    console.error("\nFAILURES:");
    for (const f of failedScript) console.error(`  ❌ ${f.label}`);
    for (const v of badVariations) console.error(`  ❌ variation ${v.id}`);
    for (const f of findings) console.error(`  ❌ audit ${f.name}: ${f.detail}`);
    process.exitCode = 1;
  }
} finally {
  await driver.close();
  await rm(dir, { recursive: true, force: true });
}
